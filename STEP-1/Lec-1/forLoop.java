
public class forLoop {
    public static void main(String[] args) {

        // Print "Hello!" 10 times
        for (int i = 1; i <= 10; i++) {
            System.out.println("Hello!");
        }

        // Print numbers from 1 to 10
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

        // Print numbers from 10 to 1
        for (int i = 10; i >= 1; i--) {
            System.out.println(i);
        }
    }
}